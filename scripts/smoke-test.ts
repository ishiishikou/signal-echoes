import { chromium } from "@playwright/test";
import { strict as assert } from "node:assert";
import { mkdirSync } from "node:fs";
const base="http://127.0.0.1:5173/";
const browser=await chromium.launch({executablePath:"/usr/bin/chromium",headless:true,
 args:["--no-sandbox","--disable-dev-shm-usage","--enable-webgl","--enable-unsafe-swiftshader","--use-gl=angle","--use-angle=swiftshader"]});
const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
const errors:string[]=[];
page.on("pageerror",e=>errors.push(e.message));
page.on("console",msg=>{if(msg.type()==="error")errors.push(msg.text())});
page.on("request",request=>{if(!request.url().startsWith(base))errors.push("EXTERNAL_REQUEST")});
mkdirSync("docs/validation",{recursive:true});
await page.goto(base,{waitUntil:"networkidle"});
await page.waitForFunction(()=>document.querySelector("#active-count")?.textContent!=="—");
const before=await page.locator("#active-count").innerText();
console.log("INITIAL_COUNT",before,"FALLBACK",await page.locator("#fallback").isVisible());
await page.screenshot({path:"docs/validation/synthetic-desktop.png",fullPage:true});
await page.locator("#play").click();
await page.waitForTimeout(700);
console.log("PLAYING",await page.locator("#playing-state").innerText());
await page.locator("#timeline").evaluate((el:HTMLInputElement)=>{el.value="80000";el.dispatchEvent(new Event("input",{bubbles:true}));});
console.log("CLOCK_AFTER_SEEK",await page.locator("#clock").innerText());
await page.getByRole("button",{name:"自分視点"}).click();
assert.equal(await page.getByRole("button",{name:"自分視点"}).getAttribute("aria-pressed"),"true");
await page.locator("#scenario").selectOption("quiet");
assert.equal(await page.locator("#active-count").innerText(),"00");
await page.locator("#scenario").selectOption("gaps");
console.log("GAPS",await page.locator("#active-count").innerText());
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:"docs/validation/synthetic-mobile.png",fullPage:true});
console.log("PAGE_ERRORS",JSON.stringify(errors));
assert.deepEqual(errors,[]);
await browser.close();
